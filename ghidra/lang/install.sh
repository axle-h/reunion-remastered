#!/usr/bin/env bash
# Builds the "x86:LE:16:Borland Pascal Real Mode" language from the local
# Ghidra's own x86 module and installs it as a Ghidra user extension.
#
# It differs from Ghidra's "x86:LE:16:Real Mode" in two ways:
#  1. Far CALL/JMP no longer assign CS before the transfer. Stock SLEIGH sets
#     CS to the target segment, and since CS survives the call the decompiler
#     believes the caller's CS changed: every later PUSH CS (string constants,
#     procedure pointers, same-segment far calls) resolved to the wrong segment.
#  2. Its compiler spec (x86-16-pascal.cspec) has Borland Pascal conventions.
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
ghidra=${GHIDRA_HOME:-$HOME/ghidra}
props=$ghidra/Ghidra/application.properties
version=$(sed -n 's/^application\.version=//p' "$props")
release=$(sed -n 's/^application\.release\.name=//p' "$props")
ext=${XDG_CONFIG_HOME:-$HOME/.config}/ghidra/ghidra_${version}_${release}/Extensions/ReunionX86
src=$ghidra/Ghidra/Processors/x86/data/languages
lang=$ext/data/languages

rm -rf "$ext"
mkdir -p "$lang"
cp "$src"/*.sinc "$src"/x86-16-real.pspec "$src"/x86-16.gdis "$lang"/
cp "$src"/x86.slaspec "$lang"/x86-pascal.slaspec
cp "$here"/x86-16-pascal.ldefs "$here"/x86-16-pascal.cspec "$lang"/

# Patch 1: drop "CS = j16;" from the real-mode far pointer operand.
sed -i -E '/^ptr1616: .*protectedMode=0/ s/\{ CS = j16; /{ /' "$lang"/ia.sinc
if grep -qE '^ptr1616: .*protectedMode=0.*CS = j16' "$lang"/ia.sinc; then
    echo "install.sh: failed to patch ptr1616 in ia.sinc" >&2
    exit 1
fi

"$ghidra"/support/sleigh "$lang"/x86-pascal.slaspec >"$ext"/sleigh.log 2>&1 || {
    cat "$ext"/sleigh.log >&2
    exit 1
}

# Function-start byte patterns are keyed by language id, so register the stock
# 16-bit patterns for ours (otherwise procs reached only through pointers are
# never found).
mkdir -p "$ext"/data/patterns
cp "$ghidra"/Ghidra/Processors/x86/data/patterns/x86-16_default_patterns.xml "$ext"/data/patterns/
cat >"$ext"/data/patterns/patternconstraints.xml <<'EOF'
<patternconstraints>
  <language id="x86:LE:16:Borland Pascal Real Mode">
    <compiler id="pascal">
      <patternfile>x86-16_default_patterns.xml</patternfile>
    </compiler>
  </language>
</patternconstraints>
EOF

touch "$ext"/Module.manifest
cat >"$ext"/extension.properties <<EOF
name=ReunionX86
description=x86 16-bit real mode with Borland Pascal 7 conventions (generated by reunion/ghidra/lang/install.sh)
author=
createdOn=$(date +%F)
version=$version
EOF

echo "Installed $ext"
