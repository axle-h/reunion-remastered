#!/usr/bin/env python3
"""Convert a picture to a 40x24 toolbar icon (palette indices) as C source.

    icon_png.py SOURCE.png NAME --crop X0,Y0,X1,Y1 [--keep X0,Y0,X1,Y1 ...]
                -o OUT.c [--preview OUT.png]

The crop is box-filtered down to 39x24 (the toolbar shows 39 columns of each
40-wide icon) and every pixel mapped to the nearest of the icon palette's
greys: indices 2 (black), 3-11 and 25 (white). The game shows icons with
ICON/ICONMAIN.PIC's palette moved up two entries (index i is its i - 2), as
the decoder adds 2 to every stored value. Column 40 is black, and
so is every pixel outside the --keep boxes (source coordinates), if given.
"""

import argparse
import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).parent))
import pic

W, H = 40, 24
GREYS = list(range(2, 12)) + [25]
BLACK = 2


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("source", type=Path)
    ap.add_argument("name")
    ap.add_argument("--crop", required=True)
    ap.add_argument("--palette", type=Path,
                    default=Path(__file__).parent.parent / "vendor/Reunion_DOS_EN/ICON/ICONMAIN.PIC")
    ap.add_argument("--keep", action="append", default=[])
    ap.add_argument("-o", "--output", type=Path, required=True)
    ap.add_argument("--preview", type=Path)
    args = ap.parse_args()

    pal = pic.load_palette(args.palette)
    rgb = {i: tuple(c * 255 // 63 for c in pal[i - 2]) for i in GREYS}
    box = tuple(int(v) for v in args.crop.split(","))
    im = Image.open(args.source).convert("RGB").crop(box).resize((W - 1, H), Image.BOX)

    px = [[BLACK] * W for _ in range(H)]
    for y in range(H):
        for x in range(W - 1):
            p = im.getpixel((x, y))
            px[y][x] = min(GREYS, key=lambda i: sum((a - b) ** 2 for a, b in zip(p, rgb[i])))
    keep = [tuple(int(v) for v in k.split(",")) for k in args.keep]
    for y in range(H):
        for x in range(W - 1):
            sx = box[0] + (x + 0.5) * (box[2] - box[0]) / (W - 1)
            sy = box[1] + (y + 0.5) * (box[3] - box[1]) / H
            if keep and not any(k[0] <= sx < k[2] and k[1] <= sy < k[3] for k in keep):
                px[y][x] = BLACK

    rows = ",\n".join("    {" + ", ".join(str(v) for v in row) + "}" for row in px)
    args.output.write_text(
        f"// Generated by tools/icon_png.py from {args.source.name}\n"
        f"// ({' '.join(sys.argv[2:])}).\n"
        f'#include "game/options.h"\n\n'
        f"const uint8_t {args.name}[{H}][{W}] = {{\n{rows}\n}};\n")
    if args.preview:
        out = Image.new("RGB", (W, H))
        for y in range(H):
            for x in range(W):
                out.putpixel((x, y), rgb[px[y][x]])
        out.resize((W * 8, H * 8), Image.NEAREST).save(args.preview)


if __name__ == "__main__":
    main()
